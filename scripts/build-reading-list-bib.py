#!/usr/bin/env python3
"""Build the Reading List's citation files from the Reading List itself.

Until October 2026 the Resources panel pointed readers to a Zotero group as
"the full collection". The group had last been edited on 8 May, held 21 papers
against the panel's 54, and belonged to an account nobody on the project could
sign in to. A second copy kept by hand drifts the moment nobody keeps it, and
that one had.

So the bibliography is now derived. This reads the study cards in the
Peer-Reviewed Research block of `panels/resources.html`, takes the DOI from each
card's link, and writes two files a reference manager imports directly:

    downloads/janvayu-reading-list.bib   BibTeX
    downloads/janvayu-reading-list.ris   RIS (Zotero, Mendeley, EndNote)

Full details (every author, the exact title, journal, volume, pages) come from
each DOI's Crossref record, because a card carries only "Pandey et al. (2026)"
and a short title. The records are cached in `data/reading-list-crossref.json`
so the build is reproducible offline and CI never needs the network.

    python3 scripts/build-reading-list-bib.py            # fetch any new DOIs, write
    python3 scripts/build-reading-list-bib.py --check    # CI: files match the panel

`--check` fails when a card has no DOI, when a DOI on the panel is missing from
the cache, or when the committed files differ from what the cache produces. A
card added to the panel without re-running this script therefore fails CI.
"""

import json
import re
import sys
import time
import html as htmllib
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PANEL = ROOT / 'panels' / 'resources.html'
CACHE = ROOT / 'data' / 'reading-list-crossref.json'
BIB = ROOT / 'downloads' / 'janvayu-reading-list.bib'
RIS = ROOT / 'downloads' / 'janvayu-reading-list.ris'
START = '<!-- PEER-REVIEWED RESEARCH.'
DOI_RE = re.compile(r'(10\.\d{4,9}/[^\s"?#]+)')


def cards():
    s = PANEL.read_text(encoding='utf-8')
    a = s.index(START)
    b = s.index('\n            <!--', a + len(START))
    out = []
    for href, title in re.findall(
            r'<div class="resource-card"[^>]*>\s*<a href="([^"]+)".*?<div class="resource-title">(.*?)</div>',
            s[a:b], re.S):
        m = DOI_RE.search(htmllib.unescape(href))
        doi = m.group(1).rstrip('/').removesuffix('/full').removesuffix('/abstract') if m else None
        out.append({'href': href, 'title': htmllib.unescape(re.sub(r'<[^>]+>', '', title)), 'doi': doi})
    return out


def fetch(doi):
    req = urllib.request.Request(
        'https://api.crossref.org/works/' + urllib.request.quote(doi),
        headers={'User-Agent': 'JanVayu reading-list builder (https://www.janvayu.in; contribute@janvayu.in)'})
    # Crossref answers 429 to bursts. Back off rather than fail the build.
    for wait in (2, 5, 15, 30, 60, None):
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                m = json.load(r)['message']
            break
        except urllib.error.HTTPError as e:
            if e.code != 429 or wait is None:
                raise
            time.sleep(wait)
    keep = ('DOI', 'title', 'author', 'container-title', 'volume', 'issue', 'page',
            'article-number', 'issued', 'published', 'publisher', 'type', 'ISSN', 'URL')
    return {k: m[k] for k in keep if k in m}


def year(m):
    for k in ('issued', 'published'):
        dp = (m.get(k) or {}).get('date-parts') or [[None]]
        if dp and dp[0] and dp[0][0]:
            return dp[0][0]
    return None


def authors(m):
    out = []
    for a in m.get('author', []):
        if a.get('family'):
            out.append((a['family'], a.get('given', '')))
        elif a.get('name'):
            out.append((a['name'], ''))
    return out


def first(m, k):
    v = m.get(k)
    return (v[0] if isinstance(v, list) and v else v) or ''


def clean(t):
    return re.sub(r'\s+', ' ', htmllib.unescape(re.sub(r'<[^>]+>', '', t or ''))).strip()


def bib_escape(t):
    return t.replace('\\', '\\\\').replace('{', '\\{').replace('}', '\\}').replace('&', '\\&').replace('%', '\\%')


def key(m, used):
    fam = authors(m)[0][0] if authors(m) else 'anon'
    base = re.sub(r'[^A-Za-z]', '', fam.encode('ascii', 'ignore').decode()) or 'anon'
    k = f'{base}{year(m) or ""}'
    n, cand = 0, k
    while cand in used:
        n += 1
        cand = k + 'abcdefghijklmnopqrstuvwxyz'[n - 1]
    used.add(cand)
    return cand


def render(entries):
    used = set()
    bib = ['% JanVayu Reading List, generated by scripts/build-reading-list-bib.py',
           '% from panels/resources.html and the Crossref record of each DOI.',
           '% Do not edit by hand. https://www.janvayu.in/#resources', '']
    ris = []
    for m in entries:
        k = key(m, used)
        au = authors(m)
        f = [('title', clean(first(m, 'title'))),
             ('author', ' and '.join(f'{fam}, {giv}'.strip(', ') for fam, giv in au)),
             ('journal', clean(first(m, 'container-title'))),
             ('year', str(year(m) or '')),
             ('volume', m.get('volume', '')), ('number', m.get('issue', '')),
             ('pages', (m.get('page') or m.get('article-number') or '').replace('-', '--')),
             ('publisher', m.get('publisher', '')),
             ('doi', m['DOI']), ('url', 'https://doi.org/' + m['DOI'])]
        bib.append(f'@article{{{k},')
        bib += [f'  {n} = {{{bib_escape(v)}}},' for n, v in f if v]
        bib += ['}', '']
        r = ['TY  - JOUR']
        r += [f'AU  - {fam}, {giv}'.rstrip(', ') for fam, giv in au]
        r += [f'TI  - {clean(first(m, "title"))}', f'T2  - {clean(first(m, "container-title"))}',
              f'PY  - {year(m) or ""}']
        if m.get('volume'): r.append(f'VL  - {m["volume"]}')
        if m.get('issue'): r.append(f'IS  - {m["issue"]}')
        pg = m.get('page') or m.get('article-number') or ''
        if pg:
            sp, _, ep = pg.partition('-')
            r.append(f'SP  - {sp}')
            if ep: r.append(f'EP  - {ep}')
        if m.get('publisher'): r.append(f'PB  - {m["publisher"]}')
        r += [f'DO  - {m["DOI"]}', f'UR  - https://doi.org/{m["DOI"]}', 'ER  - ', '']
        ris += r
    return '\n'.join(bib), '\n'.join(ris)


def main():
    check = '--check' in sys.argv
    cs = cards()
    errs = [f'card without a DOI: {c["title"]} ({c["href"]})' for c in cs if not c['doi']]
    cache = json.loads(CACHE.read_text(encoding='utf-8')) if CACHE.exists() else {}
    dois = [c['doi'] for c in cs if c['doi']]
    missing = [d for d in dois if d.lower() not in cache]
    if check:
        errs += [f'DOI on the panel but not in {CACHE.name}: {d}' for d in missing]
    else:
        for d in missing:
            print('fetching', d)
            cache[d.lower()] = fetch(d)
            # Saved after every record, so an interrupted run loses nothing.
            CACHE.write_text(json.dumps(cache, indent=1, ensure_ascii=False, sort_keys=True) + '\n', encoding='utf-8')
            time.sleep(1.5)
        cache = {d.lower(): cache[d.lower()] for d in dois}
        CACHE.write_text(json.dumps(cache, indent=1, ensure_ascii=False, sort_keys=True) + '\n', encoding='utf-8')
    if errs:
        print('FAIL -'); [print('  ' + e) for e in errs]; return 1
    entries = sorted((cache[d.lower()] for d in dict.fromkeys(dois)),
                     key=lambda m: (authors(m)[0][0].lower() if authors(m) else '', year(m) or 0))
    bib, ris = render(entries)
    if check:
        stale = [p.name for p, t in ((BIB, bib), (RIS, ris)) if not p.exists() or p.read_text(encoding='utf-8') != t]
        if stale:
            print('FAIL - out of date: ' + ', '.join(stale) + '. Run: python3 scripts/build-reading-list-bib.py')
            return 1
        print(f'PASS - {len(entries)} studies on the Reading List, all in the BibTeX and RIS files.')
        return 0
    BIB.write_text(bib, encoding='utf-8'); RIS.write_text(ris, encoding='utf-8')
    print(f'wrote {len(entries)} entries to {BIB.relative_to(ROOT)} and {RIS.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
